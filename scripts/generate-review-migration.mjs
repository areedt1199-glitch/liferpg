// Generates the quest-review migration: the guild teacher (Gemini, called by the Next.js server) checks submitted work
// against a quest's success criteria. Verdicts are written only by the server with the Supabase secret key
// (service_role) through liferpg_record_review; players can read their own. A quest needs a passed review before its
// boss fight and before completion. The snapshot and command are taken from the journal migration and extended.
// Run: node scripts/generate-review-migration.mjs
import fs from 'node:fs';
const BASE = fs.readFileSync('supabase/migrations/20261013180000_journal.sql', 'utf8');
const OUT = 'supabase/migrations/20261014120000_quest_reviews.sql';
const ms = column => `floor(extract(epoch from ${column})*1000)::bigint`;

function block(start) {
  const from = BASE.indexOf(start), to = BASE.indexOf('end $$;', from);
  if (from < 0 || to < 0) throw new Error(`not found: ${start}`);
  return BASE.slice(from, to + 'end $$;'.length);
}
function replace(text, find, replacement, count = 1) {
  const n = text.split(find).length - 1;
  if (n !== count) throw new Error(`expected ${count}× "${find}", found ${n}`);
  return text.split(find).join(replacement);
}
const REQUIRED = "if not exists(select 1 from public.quest_reviews where user_id=u and quest_id=q.id and passed_at is not null) then raise exception 'REVIEW_REQUIRED'; end if;";

let snapshot = block('create or replace function private.snapshot()');
snapshot = replace(snapshot, 'journal jsonb; xp_sum bigint;', 'journal jsonb; reviews jsonb; xp_sum bigint;');
snapshot = replace(snapshot, '  into journal from public.journal_entries where user_id=u;\n', `  into journal from public.journal_entries where user_id=u;
 select coalesce(jsonb_object_agg(r.quest_id,jsonb_build_object('attempts',r.attempts,'verdict',r.verdict,'feedback',r.feedback,'hint',r.hint,'passedAt',case when r.passed_at is null then null else ${ms('r.passed_at')} end,'updatedAt',${ms('r.updated_at')})),'{}'::jsonb)
  into reviews from public.quest_reviews r where r.user_id=u;
`);
snapshot = replace(snapshot, "'journal',journal,", "'journal',journal,'reviews',reviews,");

let command = block('create or replace function private.goal_command(action text,payload jsonb)');
// Adding or abandoning a goal clears its map, reviews included (like boss results and photos).
command = replace(command, '  delete from public.quest_evidence where user_id=u and quest_id=any(ids);\n', '  delete from public.quest_evidence where user_id=u and quest_id=any(ids);\n  delete from public.quest_reviews where user_id=u and quest_id=any(ids);\n', 2);
command = replace(command, '   -- every answered question must be right; x2 potions drunk in this fight let fewer answers win\n', `   -- every answered question must be right; x2 potions drunk in this fight let fewer answers win\n   ${REQUIRED}\n`);
command = replace(command, "  if not exists(select 1 from public.boss_results where user_id=u and quest_id=q.id and passed_at is not null) then raise exception 'BOSS_REQUIRED'; end if;\n",
  `  ${REQUIRED}\n  if not exists(select 1 from public.boss_results where user_id=u and quest_id=q.id and passed_at is not null) then raise exception 'BOSS_REQUIRED'; end if;\n`);

const sql = `-- Quest reviews by the guild teacher (generated by scripts/generate-review-migration.mjs).
-- The Next.js server asks Gemini whether submitted work meets a quest's success criteria and records the verdict with
-- the Supabase secret key; players can only read their own reviews. A passed review is required before the boss fight
-- and before completing a quest. Quests already completed are unaffected; a pass, once earned, stays.

create table public.quest_reviews(
 user_id uuid not null references public.user_progress(user_id) on delete cascade,
 quest_id text not null references public.quest_definitions(id),
 attempts integer not null default 0 check(attempts>=0),
 verdict text check(verdict in ('pass','fail')),
 feedback text not null default '' check(char_length(feedback)<=2000),
 hint text not null default '' check(char_length(hint)<=1000),
 passed_at timestamptz,
 updated_at timestamptz not null default clock_timestamp(),
 primary key(user_id,quest_id),
 foreign key(user_id,quest_id) references public.quest_progress(user_id,quest_id) on delete cascade
);
create index quest_reviews_quest_idx on public.quest_reviews(quest_id);
alter table public.quest_reviews enable row level security;
revoke all on public.quest_reviews from public,anon,authenticated;
grant select on public.quest_reviews to authenticated;
create policy own_reviews_read on public.quest_reviews for select to authenticated using((select auth.uid())=user_id);

-- Server-only: the verdict for one submission of a quest in progress. A pass is kept even if a later attempt fails.
create function private.record_review(u uuid,quest text,verdict text,feedback text,hint text) returns void language plpgsql security definer set search_path='' as $$
begin
 if verdict not in ('pass','fail') or feedback is null or hint is null then raise exception 'REVIEW_INVALID'; end if;
 if not exists(select 1 from public.quest_progress where user_id=u and quest_id=quest and status='in_progress') then raise exception 'REVIEW_QUEST_NOT_ACTIVE'; end if;
 insert into public.quest_reviews(user_id,quest_id,attempts,verdict,feedback,hint,passed_at,updated_at)
  values(u,quest,1,verdict,left(feedback,2000),left(hint,1000),case when verdict='pass' then clock_timestamp() end,clock_timestamp())
  on conflict(user_id,quest_id) do update set attempts=public.quest_reviews.attempts+1,verdict=excluded.verdict,feedback=excluded.feedback,hint=excluded.hint,
   passed_at=coalesce(public.quest_reviews.passed_at,excluded.passed_at),updated_at=excluded.updated_at;
 update public.user_progress set revision=revision+1 where user_id=u;
end $$;
grant usage on schema private to service_role;
revoke all on function private.record_review(uuid,text,text,text,text) from public,anon,authenticated;
grant execute on function private.record_review(uuid,text,text,text,text) to service_role;
create function public.liferpg_record_review(u uuid,quest text,verdict text,feedback text,hint text) returns void language sql security invoker set search_path='' as $$select private.record_review(u,quest,verdict,feedback,hint);$$;
revoke all on function public.liferpg_record_review(uuid,text,text,text,text) from public,anon,authenticated;
grant execute on function public.liferpg_record_review(uuid,text,text,text,text) to service_role;

${snapshot}
revoke all on function private.snapshot() from public,anon,authenticated;
grant execute on function private.snapshot() to authenticated;

${command}
revoke all on function private.goal_command(text,jsonb) from public,anon,authenticated;
grant execute on function private.goal_command(text,jsonb) to authenticated;
`;
fs.writeFileSync(OUT, sql);
console.log(`wrote ${OUT}`);
