// Generates the migration that grows every career/skill path map to 8 levels (advanced lessons in
// src/features/knowledge/advanced-*.ts): new quests, steps and bosses, renamed places, and progress rows for players
// who already added the goal (the first new level opens if they had passed the old last level; a finished goal reopens).
// Existing levels keep their bosses: the script stops if a shipped boss question would change.
// Run: node scripts/generate-path-levels-migration.mjs
import fs from 'node:fs';
import { loadTs } from './load-ts.mjs';
const { goalDefinitions, journeyDefinition } = loadTs('src/features/journey/definitions.ts');
const { bosses } = loadTs('src/features/boss/catalog.ts');
const { knowledgePaths } = loadTs('src/features/knowledge/index.ts');
const OUT = 'supabase/migrations/20261013120000_eight_level_paths.sql';
const SHIPPED = fs.readFileSync('supabase/migrations/20261012180000_multi_goals.sql', 'utf8');
const quote = value => "'" + String(value).replaceAll("'", "''") + "'";
const rows = (list, f) => list.map(f).join(',\n');

const base = new Map(knowledgePaths().map(k => [k.pathId, k.baseLessons]));
const goals = goalDefinitions.filter(g => g.id !== journeyDefinition.id);
const fresh = goals.flatMap(g => g.quests.slice(base.get(g.id)).map((q, i) => [q, g, base.get(g.id) + i]));
const shipped = goals.flatMap(g => g.quests.slice(0, base.get(g.id)));

const bossRow = (q, b, i) => `(${quote(b.id)},${quote(q.id)},${i + 1},${quote(b.prompt)},${quote(JSON.stringify(b.options))}::jsonb)`;
for (const q of shipped) bosses[q.id].questions.forEach((b, i) => {
  if (!SHIPPED.includes(bossRow(q, b, i)) || !SHIPPED.includes(`(${quote(b.id)},${b.answer})`)) throw new Error(`boss question changed for shipped level ${q.id}: ${b.id}`);
});
for (const [q] of fresh) for (const b of bosses[q.id].questions) if (b.options.length !== 3 || b.answer < 0 || b.answer > 2) throw new Error(`boss question ${b.id} needs 3 options`);

const ids = `(${fresh.map(([q]) => quote(q.id)).join(',')})`;
const sql = `-- Every career/skill path map grows to 8 levels (generated by scripts/generate-path-levels-migration.mjs).
-- New advanced levels follow each path's practice tasks; shipped levels keep their questions and progress.
-- Players who already added a path get the new levels: the first one opens if they had passed the old last level,
-- and a goal that was finished becomes open again (earned XP, coins and boss wins are untouched).

insert into public.quest_definitions(id,goal_id,position,title,task,place,success,minutes,xp,coins) values
${rows(fresh, ([q, g, i]) => `(${[q.id, g.id, i + 1, q.title, q.task, q.place, q.success, q.minutes, q.xp, q.coins].map(quote).join(',')})`)}
on conflict (id) do nothing;
-- Map places now spread over 8 stops; refresh the names of the shipped levels to match.
update public.quest_definitions d set place=v.place from (values
${rows(shipped, q => `(${quote(q.id)},${quote(q.place)})`)}
) as v(id,place) where d.id=v.id and d.place<>v.place;
insert into public.quest_steps(quest_id,id,position,text) values
${rows(fresh.flatMap(([q]) => q.steps.map((s, i) => [q, s, i])), ([q, s, i]) => `(${[q.id, s.id, i + 1, s.text].map(quote).join(',')})`)}
on conflict (quest_id,id) do nothing;
insert into public.boss_questions(id,quest_id,position,prompt,options) values
${rows(fresh.flatMap(([q]) => bosses[q.id].questions.map((b, i) => [q, b, i])), ([q, b, i]) => bossRow(q, b, i))}
on conflict (id) do nothing;
insert into private.boss_answers(question_id,answer) values
${rows(fresh.flatMap(([q]) => bosses[q.id].questions), b => `(${quote(b.id)},${b.answer})`)}
on conflict (question_id) do nothing;

-- Players who already have these goals: add the new levels after their current map.
insert into public.quest_progress(user_id,quest_id,status)
 select g.user_id,d.id,case when p.status='completed' then 'available' else 'locked' end
 from public.quest_definitions d
 join public.user_goals g on g.goal_id=d.goal_id
 left join public.quest_definitions prev on prev.goal_id=d.goal_id and prev.position=d.position-1
 left join public.quest_progress p on p.user_id=g.user_id and p.quest_id=prev.id
 where d.id in ${ids}
on conflict (user_id,quest_id) do nothing;
update public.user_progress u set revision=revision+1
 where exists(select 1 from public.user_goals g join public.quest_definitions d on d.goal_id=g.goal_id where g.user_id=u.user_id and d.id in ${ids});
update public.user_goals g set completed_at=null
 where completed_at is not null and exists(select 1 from public.quest_definitions d where d.goal_id=g.goal_id and d.id in ${ids});
`;
fs.writeFileSync(OUT, sql);
console.log(`wrote ${OUT}: ${fresh.length} new levels across ${goals.length} goals, ${shipped.length} shipped levels unchanged`);
