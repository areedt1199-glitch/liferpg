// Generates the 8-level migration from definitions.ts and boss/catalog.ts (single source of truth for answers).
// Run: node scripts/generate-boss-v2-migration.mjs
import fs from 'node:fs'; import { loadTs as load } from './load-ts.mjs';
const { journeyDefinition: goal } = load('src/features/journey/definitions.ts');
const { bosses } = load('src/features/boss/catalog.ts');
const quote = value => "'" + String(value).replaceAll("'", "''") + "'";
const NEW_FROM = 5; // quests before this index already exist in the database

let sql = `-- Additive: journey grows from 5 to 8 levels; level N boss has N+2 questions (generated by scripts/generate-boss-v2-migration.mjs).
-- Existing rewards, focus sessions and boss wins are kept. Players who finished level 5 continue at level 6.
`;
for (const [index, q] of goal.quests.entries()) {
  if (index < NEW_FROM) continue;
  sql += `insert into public.quest_definitions(id,goal_id,position,title,task,place,success,minutes,xp,coins) values (${[q.id, goal.id, index + 1, q.title, q.task, q.place, q.success, q.minutes, q.xp, q.coins].map(quote).join(',')}) on conflict (id) do nothing;\n`;
  for (const [i, step] of q.steps.entries()) sql += `insert into public.quest_steps(quest_id,id,position,text) values (${[q.id, step.id, i + 1, step.text].map(quote).join(',')}) on conflict (quest_id,id) do nothing;\n`;
}
const firstNew = goal.quests[NEW_FROM].id, lastOld = goal.quests[NEW_FROM - 1].id;
sql += `
insert into public.quest_progress(user_id,quest_id,status)
 select p.user_id,d.id,'locked' from public.user_progress p cross join public.quest_definitions d
 where d.goal_id=${quote(goal.id)} and d.position>${NEW_FROM} on conflict do nothing;
update public.quest_progress x set status='available' from public.quest_progress done
 where x.quest_id=${quote(firstNew)} and x.status='locked' and done.user_id=x.user_id and done.quest_id=${quote(lastOld)} and done.status='completed';
update public.user_progress set goal_completed_at=null,revision=revision+1 where goal_completed_at is not null;

-- Boss results now record how many questions they were graded against (legacy rows: 3).
alter table public.boss_results add column total integer not null default 3;
do $$ declare c record; begin
 for c in select conname from pg_constraint where conrelid='public.boss_results'::regclass and contype='c' loop
  execute format('alter table public.boss_results drop constraint %I',c.conname); end loop;
 for c in select conname from pg_constraint where conrelid='private.boss_answers'::regclass and contype='c' loop
  execute format('alter table private.boss_answers drop constraint %I',c.conname); end loop;
end $$;
alter table public.boss_results add constraint boss_results_total_check check(total between 3 and 10),
 add constraint boss_results_score_check check(score between 0 and total), add constraint boss_results_attempts_check check(attempts>0),
 add constraint boss_results_pass_check check((score=total)=(passed_at is not null));
alter table private.boss_answers add constraint boss_answers_answer_check check(answer between 0 and 3);

delete from private.boss_answers;
delete from public.boss_questions;
insert into public.boss_questions(id,quest_id,position,prompt,options) values
${Object.entries(bosses).flatMap(([questId, b]) => b.questions.map((q, i) => `(${quote(q.id)},${quote(questId)},${i + 1},${quote(q.prompt)},${quote(JSON.stringify(q.options))}::jsonb)`)).join(',\n')};
insert into private.boss_answers(question_id,answer) values
${Object.values(bosses).flatMap(b => b.questions.map(q => `(${quote(q.id)},${q.answer})`)).join(',\n')};

alter function private.command(text,jsonb) rename to command_boss3;
revoke all on function private.command_boss3(text,jsonb) from public,anon,authenticated;
create function private.command(action text,payload jsonb) returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid;q text:=payload->>'questId';p public.user_progress;s text;n integer;score integer;answers jsonb:=payload->'answers';
begin
 if action<>'boss_attempt' then return private.command_boss3(action,payload);end if;
 u:=private.ensure_user();select * into p from public.user_progress where user_id=u;
 select status into s from public.quest_progress where user_id=u and quest_id=q;
 if s is distinct from 'in_progress' or p.active_quest_id is distinct from q then raise exception 'QUEST_NOT_ACTIVE';end if;
 if exists(select 1 from public.quest_steps t where t.quest_id=q and not exists(select 1 from public.checklist c where c.user_id=u and c.quest_id=q and c.step_id=t.id))then raise exception 'CHECKLIST_INCOMPLETE';end if;
 if exists(select 1 from public.boss_results where user_id=u and quest_id=q and passed_at is not null)then return private.snapshot();end if;
 select count(*) into n from public.boss_questions where quest_id=q;
 if n=0 or jsonb_typeof(answers) is distinct from 'object' then raise exception 'BOSS_ANSWERS_INVALID';end if;
 if (select count(*) from jsonb_object_keys(answers))<>n or exists(select 1 from public.boss_questions b where b.quest_id=q and (jsonb_typeof(answers->b.id) is distinct from 'number' or (answers->>b.id)!~'^[0-9]$' or (answers->>b.id)::integer>=jsonb_array_length(b.options)))then raise exception 'BOSS_ANSWERS_INVALID';end if;
 select count(*) into score from public.boss_questions b join private.boss_answers a on a.question_id=b.id where b.quest_id=q and (answers->>b.id)::integer=a.answer;
 insert into public.boss_results(user_id,quest_id,score,attempts,passed_at,total) values(u,q,score,1,case when score=n then clock_timestamp() end,n)
  on conflict(user_id,quest_id) do update set score=excluded.score,total=excluded.total,attempts=public.boss_results.attempts+1,passed_at=excluded.passed_at;
 update public.user_progress set revision=revision+1 where user_id=u;
 return private.snapshot();
end $$;
revoke all on function private.command(text,jsonb) from public,anon,authenticated;
grant execute on function private.command(text,jsonb) to authenticated;

alter function private.snapshot() rename to snapshot_practice;
revoke all on function private.snapshot_practice() from public,anon,authenticated;
create function private.snapshot() returns jsonb language plpgsql security definer set search_path='' as $$
declare result jsonb;bosses jsonb;
begin
 result:=private.snapshot_practice();
 select coalesce(jsonb_object_agg(quest_id,jsonb_build_object('score',score,'total',total,'attempts',attempts,'passedAt',case when passed_at is null then null else floor(extract(epoch from passed_at)*1000)::bigint end)),'{}'::jsonb)
  into bosses from public.boss_results where user_id=auth.uid();
 return jsonb_set(result,'{progress,bosses}',bosses);
end $$;
revoke all on function private.snapshot() from public,anon,authenticated;
grant execute on function private.snapshot() to authenticated;
`;
fs.writeFileSync('supabase/migrations/20261011120000_eight_levels.sql', sql);
console.log('wrote supabase/migrations/20261011120000_eight_levels.sql');
